"""
Tests for recovering from, and reporting, a long Octopus token mint block.

In Nov 2026 several instances had their token mint refused for days while public rate downloads
kept the component looking healthy:
- An edge/WAF block stuck to one HTTP session, while a fresh process on the same key minted at once,
  so a blocked mint is retried from a fresh session
- A KT-CT-1199 refusal stayed tripped under an hourly retry, so it backs off for longer
- The component reports itself failed once the mint has been refused for an hour
"""

import asyncio
import json
from datetime import datetime, timedelta, timezone
from unittest.mock import AsyncMock, MagicMock
from octopus import OctopusAPI, OctopusEnergyApiClient, integration_context_header, OCTOPUS_MINT_UNHEALTHY_AFTER_SECONDS
from utils import Backoff, TOKEN_MINT_BACKOFF_MAX_SECONDS, TOKEN_MINT_RATE_LIMIT_BACKOFF_MAX_SECONDS

RATE_LIMIT_BODY = json.dumps({"errors": [{"message": "Too many requests.", "extensions": {"errorCode": "KT-CT-1199"}}]})
TOKEN_BODY = json.dumps({"data": {"obtainKrakenToken": {"token": "fresh-token"}}})

CLOUDFRONT_403_BODY = (
    '<!DOCTYPE HTML PUBLIC "-//W3C//DTD HTML 4.01 Transitional//EN">\n'
    "<HTML><HEAD><TITLE>ERROR: The request could not be satisfied</TITLE></HEAD>\n"
    "<BODY><H1>403 ERROR</H1><H2>The request could not be satisfied.</H2>\n"
    "Request blocked.\nGenerated by cloudfront (CloudFront)\n</BODY></HTML>"
)


def _make_response(status, body, headers=None):
    """Build a mock aiohttp response whose text() returns body."""
    response = MagicMock()
    response.status = status
    response.text = AsyncMock(return_value=body)
    response.headers = headers if headers is not None else {}
    response.request_info = MagicMock()
    response.request_info.headers = {integration_context_header: "test-context"}
    response.__aenter__ = AsyncMock(return_value=response)
    response.__aexit__ = AsyncMock(return_value=None)
    return response


def _make_api(my_predbat, *responses):
    """Build an OctopusAPI whose mint POSTs return the given responses in turn, recording session resets in order with the POSTs."""
    api = OctopusAPI(my_predbat, key="test-api-key", account_id="test-account", automatic=False)
    session = MagicMock()
    queue = list(responses)
    events = []

    def post(*args, **kwargs):
        """Hand out the next queued response, repeating the last."""
        events.append("post")
        return queue.pop(0) if len(queue) > 1 else queue[0]

    async def reset():
        """Record a session reset."""
        events.append("reset")

    session.post = MagicMock(side_effect=post)
    api.api.async_create_client_session = AsyncMock(return_value=session)
    api.api.async_reset_client_session = AsyncMock(side_effect=reset)
    api.save_octopus_cache = AsyncMock()
    api.logged = []
    api.log = lambda message: api.logged.append(str(message))
    return api, events


def _expire_mint_backoff(api):
    """Move the mint backoff window into the past, as if it had elapsed."""
    api.token_mint_backoff.until = datetime.now(timezone.utc) - timedelta(seconds=1)


def test_octopus_mint_block_recovery_wrapper(my_predbat):
    return asyncio.run(test_octopus_mint_block_recovery(my_predbat))


async def test_octopus_mint_block_recovery(my_predbat):
    """
    Tests:
    - Test 1: Backoff records when a run of refusals started, keeps it across refusals, and clears it
    - Test 2: Backoff.start takes a per-refusal cap in place of the schedule's own
    - Test 3: A mint retried after an edge/WAF block starts a fresh session first
    - Test 4: The first mint, and a retry after a rate limit, keep the existing session
    - Test 5: A KT-CT-1199 mint backs off past the hour, up to the rate limit cap
    - Test 6: An edge/WAF blocked mint is still capped at the hour
    - Test 7: The component stays healthy through a short mint block, then reports failed with a reason
    - Test 8: A successful mint makes the component healthy again
    - Test 9: async_reset_client_session closes the session and the next request opens a new one
    """
    print("**** Running Octopus mint block recovery tests ****")
    failed = False

    def check(condition, message):
        """Print and record a failed check."""
        nonlocal failed
        if not condition:
            print("ERROR: " + message)
            failed = True
        return condition

    # Test 1
    print("\n*** Test 1: Backoff.started_at ***")
    backoff = Backoff(300, 3600)
    check(backoff.started_at is None, "a new backoff has no start time")
    before = datetime.now(timezone.utc)
    backoff.start("edge/WAF blocked")
    first = backoff.started_at
    check(first is not None and first >= before and first.utcoffset() == timedelta(0), "first refusal should record an aware UTC start, got {!r}".format(first))
    backoff.start("edge/WAF blocked")
    check(backoff.started_at == first, "a later refusal must not move the start")
    backoff.clear()
    check(backoff.started_at is None, "clear should forget the start")

    # Test 2
    print("\n*** Test 2: Backoff.start per-refusal cap ***")
    backoff = Backoff(300, 3600)
    delays = [backoff.start("rate limited", max_seconds=4 * 3600) for _ in range(8)]
    check(delays == [300, 600, 1200, 2400, 4800, 9600, 14400, 14400], "doubling past the schedule's own cap, got {}".format(delays))
    backoff = Backoff(300, 3600)
    delays = [backoff.start("rate limited") for _ in range(6)]
    check(delays == [300, 600, 1200, 2400, 3600, 3600], "without a cap the schedule is unchanged, got {}".format(delays))
    check(Backoff(300, 3600).start("rate limited", retry_after=86400, max_seconds=7200) == 7200, "Retry-After is held to the per-refusal cap")

    # Test 3
    print("\n*** Test 3: retry after an edge/WAF block starts a fresh session ***")
    api, events = _make_api(my_predbat, _make_response(403, CLOUDFRONT_403_BODY), _make_response(200, TOKEN_BODY))
    check(await api.async_refresh_token() is None, "a blocked mint gives no token")
    check(events == ["post"], "the first mint should not reset the session, got {}".format(events))
    _expire_mint_backoff(api)
    token = await api.async_refresh_token()
    check(token == "fresh-token", "the retry from a fresh session should mint, got {}".format(token))
    check(events == ["post", "reset", "post"], "the session should be reset before the retried mint, got {}".format(events))
    check(any("fresh HTTP session" in line for line in api.logged), "the reset should be logged: {}".format(api.logged))
    check(api.token_mint_backoff.count == 0 and api.token_mint_backoff.started_at is None, "a successful mint should clear the backoff")

    # Test 4
    print("\n*** Test 4: no reset on the first mint or after a rate limit ***")
    api, events = _make_api(my_predbat, _make_response(200, RATE_LIMIT_BODY), _make_response(200, TOKEN_BODY))
    await api.async_refresh_token()
    _expire_mint_backoff(api)
    await api.async_refresh_token()
    check(events == ["post", "post"], "a rate-limited mint is per key, so the session should be kept, got {}".format(events))

    # Test 5
    print("\n*** Test 5: KT-CT-1199 backs off past the hour ***")
    api, events = _make_api(my_predbat, _make_response(200, RATE_LIMIT_BODY))
    delays = []
    for _ in range(8):
        before = datetime.now(timezone.utc)
        await api.async_refresh_token()
        delays.append(round((api.token_mint_backoff.until - before).total_seconds()))
        _expire_mint_backoff(api)
    check(max(delays) >= TOKEN_MINT_RATE_LIMIT_BACKOFF_MAX_SECONDS - 1, "rate-limited mint should reach the longer cap, got {}".format(delays))
    check(max(delays) <= TOKEN_MINT_RATE_LIMIT_BACKOFF_MAX_SECONDS + 1, "rate-limited mint should not exceed its cap, got {}".format(delays))
    check(any("Backing off for {}s".format(TOKEN_MINT_RATE_LIMIT_BACKOFF_MAX_SECONDS) in line for line in api.logged), "the long backoff should be logged: {}".format(api.logged))

    # Test 6
    print("\n*** Test 6: an edge/WAF blocked mint stays capped at the hour ***")
    api, events = _make_api(my_predbat, _make_response(403, CLOUDFRONT_403_BODY))
    delays = []
    for _ in range(8):
        before = datetime.now(timezone.utc)
        await api.async_refresh_token()
        delays.append(round((api.token_mint_backoff.until - before).total_seconds()))
        _expire_mint_backoff(api)
    check(max(delays) <= TOKEN_MINT_BACKOFF_MAX_SECONDS + 1, "edge-blocked mint should stay capped at {}s, got {}".format(TOKEN_MINT_BACKOFF_MAX_SECONDS, delays))

    # Test 7
    print("\n*** Test 7: unhealthy after an hour of refused mints ***")
    api = OctopusAPI(my_predbat, key="test-api-key", account_id="test-account", automatic=False)
    api.api_started = True
    api.account_data = {"account": {"number": "A-123"}}
    check(api.is_alive() is True and api.health_message() is None, "a healthy component reports alive with no message")
    api.token_mint_backoff.start("edge/WAF blocked")
    check(api.is_alive() is True, "a mint block shorter than the threshold should not fail the component")
    api.token_mint_backoff.started_at = datetime.now(timezone.utc) - timedelta(seconds=OCTOPUS_MINT_UNHEALTHY_AFTER_SECONDS + 3 * 3600)
    check(api.is_alive() is False, "a mint refused for over the threshold should fail the component")
    message = api.health_message()
    check(message is not None and "blocked" in message and "4h" in message, "health message should say the sign-in is blocked and for how long, got {!r}".format(message))
    api.token_mint_backoff.reason = "rate limited"
    message = api.health_message()
    check(message is not None and "rate limited" in message, "health message should name a rate limit, got {!r}".format(message))
    api.account_data = {}
    check(api.is_alive() is False, "no account data is still unhealthy")

    # Test 8
    print("\n*** Test 8: a successful mint restores health ***")
    api, events = _make_api(my_predbat, _make_response(200, TOKEN_BODY))
    api.api_started = True
    api.account_data = {"account": {"number": "A-123"}}
    api.token_mint_backoff.start("edge/WAF blocked")
    api.token_mint_backoff.started_at = datetime.now(timezone.utc) - timedelta(seconds=OCTOPUS_MINT_UNHEALTHY_AFTER_SECONDS + 60)
    _expire_mint_backoff(api)
    check(api.is_alive() is False, "precondition: unhealthy while blocked")
    await api.async_refresh_token()
    check(api.is_alive() is True and api.health_message() is None, "a successful mint should make the component healthy again")

    # Test 9
    print("\n*** Test 9: async_reset_client_session ***")
    client = OctopusEnergyApiClient("test-api-key", lambda message: None)
    await client.async_reset_client_session()
    check(client.session is None, "resetting with no session is harmless")
    old = MagicMock()
    old.close = AsyncMock()
    client.session = old
    await client.async_reset_client_session()
    check(old.close.await_count == 1, "the old session should be closed")
    check(client.session is None, "the session should be dropped")
    new = await client.async_create_client_session()
    check(new is not old and new is not None, "the next request should open a new session")
    await new.close()

    if failed:
        print("**** Octopus mint block recovery tests FAILED ****")
    else:
        print("**** All Octopus mint block recovery tests PASSED ****")
    return failed
